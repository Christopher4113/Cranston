// Runs the full pipeline on the sample client, scores it against data/ground_truth.json,
// and writes results/metrics.json, results/findings.md and public/demo/run.json.
// With no ANTHROPIC_API_KEY it uses cached LLM output if present, else the deterministic template explainer.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { parseQbo } from "../lib/import/qbo";
import { runPipeline } from "../lib/pipeline";

interface Truth { id: string; type?: string; check: string; account?: string; amount?: number; txn_ids: string[]; description: string }
const truth = JSON.parse(readFileSync("data/ground_truth.json", "utf8")) as { plants: Truth[]; decoys: Truth[] };
const dir = "data/qbo";
const books = parseQbo(Object.fromEntries(readdirSync(dir).map((f) => [f, readFileSync(`${dir}/${f}`, "utf8")])));

runPipeline(books).then((run) => {
const F = run.findings;
// A plant counts only when the check designed for it fires on it (a different check citing the same txn doesn't count).
const catches = (p: Truth) => F.filter((f) => f.check_id === p.check).filter((f) => f.cited_txn_ids.some((t) => p.txn_ids.includes(t)) || (!p.txn_ids.length && f.check_id === p.check && f.accounts.includes(p.account!)));
const plants = truth.plants.map((p) => ({ ...p, caught_by: catches(p).map((f) => f.id) }));
const decoys = truth.decoys.map((d) => ({ ...d, flagged_by: F.filter((f) => f.cited_txn_ids.some((t) => d.txn_ids.includes(t))).map((f) => f.id) }));
const matched = new Set(plants.flatMap((p) => p.caught_by));
const unmatched = F.filter((f) => !matched.has(f.id));
const sep = run.reconciliations.filter((r) => r.month === run.period);
const caught = plants.filter((p) => p.caught_by.length).length;
const falseDecoys = decoys.filter((d) => d.flagged_by.length).length;
const checks = [...new Set(truth.plants.map((p) => p.check))].sort();

const metrics = {
  client: run.client, period: run.period,
  reconciliation_baseline: { accounts_reconciled: `${sep.filter((r) => r.difference === 0).length}/${sep.length}`, month_ends_reconciled: `${run.reconciliations.filter((r) => r.difference === 0).length}/${run.reconciliations.length}`, plants_caught: `0/${plants.length}` },
  close_review: { plants_caught: `${caught}/${plants.length}`, decoys_flagged: `${falseDecoys}/${decoys.length}`, other_false_alarms: unmatched.length, findings: F.length },
  per_check: Object.fromEntries(checks.map((c) => { const ps = plants.filter((p) => p.check === c); return [c, `${ps.filter((p) => p.caught_by.length).length}/${ps.length}`]; })),
  explanations: { verified: `${run.stats.verified}/${F.length}`, entries_balanced: `${F.filter((f) => Math.abs(f.proposed_entry.reduce((s, l) => s + l.debit - l.credit, 0)) < 0.005).length}/${F.length}`, source: [...new Set(F.map((f) => f.source))] },
  cost: { llm_usd: run.stats.llm_usd, ms: run.stats.ms, transactions: run.stats.transactions },
  plants: plants.map(({ id, type, check, caught_by }) => ({ id, type, check, caught_by })),
  decoys: decoys.map(({ id, check, flagged_by }) => ({ id, check, flagged_by })),
  other_false_alarms: unmatched.map((f) => ({ id: f.id, title: f.title })),
};
mkdirSync("results", { recursive: true });
mkdirSync("public/demo", { recursive: true });
writeFileSync("results/metrics.json", JSON.stringify(metrics, null, 2));
writeFileSync("public/demo/run.json", JSON.stringify({ ...run, eval: { planted: plants.length, caught, decoys: decoys.length, decoys_flagged: falseDecoys, other_false_alarms: unmatched.length, false_findings: unmatched.map((f) => f.id) } }));

const tour = ["C2", "C1", "C4"].map((c) => F.find((f) => f.check_id === c)!);
writeFileSync("results/findings.md", `# Close Review: findings

Synthetic client: ${run.client} (fictional). Period: ${run.period}. Review rules are an illustrative sample checklist, not accounting advice.
Generated by \`npm run eval\` from \`data/ground_truth.json\`.

## Headline

- **Bank & card reconciliation:** ${metrics.reconciliation_baseline.accounts_reconciled} accounts reconciled at $0.00 difference at Sep 30 (${metrics.reconciliation_baseline.month_ends_reconciled} month-ends). It catches **0/${plants.length}** planted errors, by design.
- **Close Review:** caught **${caught}/${plants.length}** planted errors. Decoys flagged: **${falseDecoys}/${decoys.length}**. Other false alarms: **${unmatched.length}**.
- Explanations verified: ${metrics.explanations.verified}; entries balanced: ${metrics.explanations.entries_balanced}; explainer source: ${metrics.explanations.source.join(", ")}.
- Cost per close: $${run.stats.llm_usd} in LLM calls, ${run.stats.ms} ms over ${run.stats.transactions} transactions.

| Check | Plants caught |
|---|---|
${Object.entries(metrics.per_check).map(([c, v]) => `| ${c} | ${v} |`).join("\n")}

## Plants

| # | Planted error | Check | Caught by |
|---|---|---|---|
${plants.map((p) => `| ${p.id} | ${p.description} | ${p.check} | ${p.caught_by.join(", ") || "**missed**"} |`).join("\n")}

## The three tour examples

${tour.map((f) => `### ${f.title}\n\n${f.why ?? "_explanation unavailable_"}\n\n${f.proposed_entry.map((l) => `- ${l.account} ${l.debit ? `Dr ${l.debit.toFixed(2)}` : `Cr ${l.credit.toFixed(2)}`}: ${l.memo}`).join("\n")}\n`).join("\n")}
## False alarms

${unmatched.length ? unmatched.map((f) => `- **${f.id}** ${f.title}`).join("\n") : "None."}

## What's hard

- **Vendor-name matching.** "Bay Area Espresso Tech" and "Bay Area Espresso Supply" score ≥0.85 on Jaro-Winkler, the same as a real near-duplicate. Name similarity alone would flag them; the check also requires the same invoice number, or the same amount with no conflicting invoice numbers.
- **Flux thresholds.** A swing is only meaningful against a clean baseline. Other findings' transactions are removed first (so the insurance prepayment doesn't also show up as a flux swing), and new memo'd items count as explained. The one false alarm shows the limit: September cups look 36% low only because August's baseline includes a legitimate $1,650 bulk order (decoy D4). A one-off in the baseline still moves the average; a median or a longer baseline would help.
- **Missing liabilities.** P14 (unremitted Q2 sales tax) is missed: nothing in the sample checklist ages balance-sheet liabilities. A "stale liability" check (balance unchanged for 60+ days) would catch it.

## Limitations

- Synthetic data, one fictional client, one quarter. Planted errors were designed by the same person who wrote the checks.
- The review rules are a small illustrative checklist with hand-picked thresholds.
- No real QuickBooks connection: imports QBO-shaped CSV exports only. Nothing is written back to a ledger.
- Explanations in this run came from: ${metrics.explanations.source.join(", ")}. "template" is the deterministic no-key explainer; run with \`ANTHROPIC_API_KEY\` set to regenerate with Claude (results are cached in \`cache/explain/\`).
`);
console.log(JSON.stringify({ ...metrics, plants: undefined, decoys: undefined }, null, 2));
});
